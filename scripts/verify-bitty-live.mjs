// Read-only publication verification; credentials and private profile remain in memory.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const state=JSON.parse(readFileSync('.data/public/state.json','utf8').replace(/^\uFEFF/,''));
const origin=state.publicOrigin??state.origin;
const login=await fetch(origin+'/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json',Origin:origin},body:JSON.stringify({password:state.password})});
assert.equal(login.status,200,'Existing password');
const cookie=login.headers.get('set-cookie')?.split(';')[0];
const api=async path=>{const r=await fetch(origin+path,{headers:{cookie,Origin:origin}});assert.equal(r.status,200,path);return r.json();};
const backup=await api('/api/data/export');
const before=JSON.parse(readFileSync('.data/public/bitty-before-export.json','utf8'));
const old=before.state.profile;
assert.equal(backup.state.profile.mascotVersion,1);
assert.equal(backup.state.profile.skin,old.mascotVersion===1?old.skin:!old.skin||old.skin==='original'?'bitty':old.skin,'Selected mascot retained or default upgraded once');
assert.ok(backup.state.inventory.includes('bitty'));
assert.equal(backup.state.xp,before.state.xp);assert.equal(backup.state.gems,before.state.gems);
const binaryResponse=await fetch(origin+'/mascots/bitty/bitty.riv');
assert.equal(binaryResponse.status,200);assert.match(binaryResponse.headers.get('content-type'),/application\/octet-stream/);
const binary=Buffer.from(await binaryResponse.arrayBuffer()),local=readFileSync('public/mascots/bitty/bitty.riv');
assert.deepEqual(binary,local);assert.equal(binary.subarray(0,4).toString(),'RIVE');assert.ok(binary.length<200000);
const contractResponse=await fetch(origin+'/mascots/bitty/contract.json');assert.equal(contractResponse.status,200);
const contract=await contractResponse.json();assert.equal(contract.states.length,27);assert.equal(contract.scriptFree,true);
const svgResponse=await fetch(origin+'/mascots/bitty/bitty-rig.svg');assert.equal(svgResponse.status,200);assert.match(svgResponse.headers.get('content-type'),/image\/svg\+xml/);
const html=await (await fetch(origin+'/mascot')).text();
const staged=readFileSync('output/ml-dist/index.html','utf8');
const entry=staged.match(/<script[^>]+src="([^"]+)"/)?.[1];assert.ok(entry&&html.includes(entry));
const assetEntry=await fetch(origin+entry);assert.equal(assetEntry.status,200);
const bundle=await assetEntry.text();
const chunks=[...new Set([...bundle.matchAll(/assets\/RiveMascot[^"']+\.js/g)].map(m=>'/'+m[0]))];
assert.equal(chunks.length,1,'Lazy Rive adapter available');
const riveJsResponse=await fetch(origin+chunks[0]);assert.equal(riveJsResponse.status,200);
const riveJs=await riveJsResponse.text();
const wasmPaths=[...new Set([...riveJs.matchAll(/\/?assets\/rive(?:_fallback)?-[\w-]+\.wasm/g)].map(m=>'/'+m[0].replace(/^\//,'')))];
assert.equal(wasmPaths.length,2,'Local main and fallback WASM');
for(const path of wasmPaths){const r=await fetch(origin+path);assert.equal(r.status,200);assert.match(r.headers.get('content-type'),/application\/wasm/);const data=new Uint8Array(await r.arrayBuffer());assert.deepEqual([...data.slice(0,4)],[0,97,115,109]);}
const report={origin,existingPassword:true,progressVerification:'verify-expansion-live.mjs',profileMigration:true,oldMascotChoiceRetained:true,XPUnchanged:true,gemsUnchanged:true,freeBittyOwned:true,rivBytes:binary.length,sha256:createHash('sha256').update(binary).digest('hex'),requiredTimelines:27,scriptFree:true,testedFrontend:true,lazyRiveChunk:true,sameOriginWasm:true};
writeFileSync('output/bitty-live-report.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
